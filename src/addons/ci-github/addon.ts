import { readFileInside } from '../../core/fs-safe.js';
import type { PackageManagerId } from '../../core/pm.js';
import type { Addon, AddonContext } from '../types.js';

// Actions are pinned to full commit SHAs (resolved 2026-10-26) so a moved tag cannot
// change what runs in CI. Update them deliberately, together with the comments.
const ACTIONS = {
  checkout: 'actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1',
  setupNode: 'actions/setup-node@949feb2413d6458794dcd2491c4babbbce0c15c1 # v7.1.0',
  setupPnpm: 'pnpm/action-setup@ea17c68df8912ef543352723c149a84f56e3d413 # v6.1.0',
};

/** Run in this order when the project defines them. */
const CHECK_SCRIPTS = ['typecheck', 'lint', 'format:check', 'test', 'build'];

export const WORKFLOW_PATH = '.github/workflows/ci.yml';

function packageManagerOf(ctx: AddonContext): PackageManagerId | undefined {
  const supported = ctx.project.packageManagers.filter(
    (pm): pm is PackageManagerId => pm === 'npm' || pm === 'pnpm',
  );
  return supported.length === 1 ? supported[0] : undefined;
}

export function renderWorkflow(ctx: AddonContext): string {
  const pm = packageManagerOf(ctx);
  if (!pm) throw new Error('package manager could not be determined');
  const scripts = CHECK_SCRIPTS.filter((s) => ctx.project.manifest?.scripts?.[s] !== undefined);
  const pnpmVersion = ctx.project.manifest?.packageManager?.startsWith('pnpm@')
    ? undefined
    : (ctx.pnpmVersion?.split('.')[0] ?? undefined);

  const lines = [
    '# Generated by StackJoist (ci-github add-on). Edit freely; StackJoist will not',
    '# overwrite your changes on update (it writes ci.yml.stackjoist-new instead).',
    'name: CI',
    '',
    'on:',
    '  push:',
    '    branches: [main]',
    '  pull_request:',
    '',
    'permissions:',
    '  contents: read',
    '',
    'concurrency:',
    '  group: ci-${{ github.ref }}',
    '  cancel-in-progress: true',
    '',
    'jobs:',
    '  verify:',
    '    runs-on: ubuntu-latest',
    '    timeout-minutes: 20',
    '    steps:',
    `      - uses: ${ACTIONS.checkout}`,
    '        with:',
    '          persist-credentials: false',
  ];
  if (pm === 'pnpm') {
    lines.push(`      - uses: ${ACTIONS.setupPnpm}`);
    if (pnpmVersion) lines.push('        with:', `          version: ${pnpmVersion}`);
  }
  lines.push(
    `      - uses: ${ACTIONS.setupNode}`,
    '        with:',
    '          node-version: lts/*',
    `          cache: ${pm}`,
    `      - run: ${pm === 'pnpm' ? 'pnpm install --frozen-lockfile' : 'npm ci'}`,
    ...scripts.map((s) => `      - run: ${pm} run ${s}`),
  );
  return `${lines.join('\n')}\n`;
}

export const ciGithub: Addon = {
  id: 'ci-github',
  title: 'GitHub Actions CI',
  description: "CI workflow that installs with the lockfile and runs the project's checks",
  version: '0.1.0',
  incompatibility(ctx) {
    if (!ctx.project.manifest) return 'no package.json found';
    const pms = ctx.project.packageManagers;
    if (pms.length === 0)
      return 'no lockfile found: install dependencies and commit the lockfile first';
    if (pms.length > 1) return `several lockfiles found (${pms.join(', ')}): keep only one`;
    if (!packageManagerOf(ctx)) return `${pms[0] ?? 'this package manager'} is not supported`;
    if (pms[0] === 'pnpm' && !ctx.project.manifest.packageManager && !ctx.pnpmVersion) {
      return 'pnpm version unknown: add a "packageManager" field to package.json or install pnpm';
    }
    const scripts = ctx.project.manifest.scripts ?? {};
    if (!CHECK_SCRIPTS.some((s) => s in scripts)) {
      return `package.json has none of the scripts CI would run (${CHECK_SCRIPTS.join(', ')})`;
    }
    return undefined;
  },
  changes(ctx) {
    return Promise.resolve([
      { kind: 'managed', path: WORKFLOW_PATH, content: renderWorkflow(ctx) },
    ]);
  },
  async verify(root) {
    const text = await readFileInside(root, WORKFLOW_PATH);
    return [
      { name: `${WORKFLOW_PATH} present`, status: text ? 'PASS' : 'FAIL' },
      {
        name: 'workflow runs on GitHub',
        status: 'NOT RUN',
        detail: 'runs after you push; check the Actions tab',
      },
    ];
  },
  limitations: [
    'Linux runner with the current Node.js LTS only; add a matrix if you need more.',
    'Runs only scripts that exist in package.json when the add-on is applied.',
  ],
  nextSteps: ['Commit .github/workflows/ci.yml and push to see it run in the Actions tab.'],
};
